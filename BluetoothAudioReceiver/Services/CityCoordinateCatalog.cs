    public static bool TryResolve(string? city, out CityCoordinate coordinate)
    {
        var normalized = (city ?? string.Empty).Trim();
        if (normalized.EndsWith("市", StringComparison.Ordinal))
        {
            normalized = normalized[..^1];
        }

        return Cities.TryGetValue(normalized, out coordinate);
    }
